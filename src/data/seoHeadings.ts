/**
 * Zentrale, verbindliche Überschriften-Konfiguration für sämtliche SEO-Seiten.
 *
 * Jede indexierbare SEO-URL braucht hier einen expliziten Eintrag. Es gibt
 * bewusst KEINEN generischen Fallback für vorhandene SEO-Seiten – ein
 * fehlender Eintrag soll den Vollständigkeitstest (siehe
 * `src/data/seoHeadings.test.ts`) fehlschlagen lassen, nicht eine
 * automatisch generierte Überschrift produzieren.
 *
 * Fallbacks sind ausschließlich für Fehlerseiten und nicht indexierbare
 * technische Zustände zulässig (siehe `_notFound` weiter unten).
 */

export interface SeoHeadingSet {
  /** Exakte, sichtbare H1 der Seite. Genau eine pro Seite. */
  h1: string;
  /**
   * Teilstring innerhalb von h1, der in Glanzwerk-Hellblau hervorgehoben wird
   * (bestehendes Designmuster). Optional – nicht jede H1 braucht eine
   * Hervorhebung.
   */
  h1Highlight?: string;
  /** Alle tatsächlich sichtbaren inhaltlichen H2 der Seite, in Reihenfolge. */
  sectionHeadings: string[];
  /** H2 direkt über dem FAQ-Block, falls die Seite FAQ besitzt. */
  faqHeading?: string;
  /** H2/Titel des abschließenden bzw. mittleren CTA-Blocks, falls vorhanden. */
  ctaHeading?: string;
  /** Nur Wissen-Artikel: H2 über den verwandten Leistungen am Artikelende. */
  relatedServicesHeading?: string;
  /** Nur Wissen-Artikel: H2 über den weiteren Artikelempfehlungen am Artikelende. */
  moreArticlesHeading?: string;
  /** Optionaler zweiter CTA-Block (z. B. 3-Monate-Test-Zwischen-CTA). */
  secondaryCtaHeading?: string;
  /** Meta-Titel, sofern er aktuell aus derselben generischen Logik wie H1 erzeugt wird. */
  metaTitle?: string;
  /** Kurzbeschreibung des inhaltlichen Kernthemas der Seite (für das Audit-Dokument). */
  mainTopic: string;
  /** Ähnlichste interne URL, gegen die diese Seite abgegrenzt wurde. */
  mostSimilarUrl?: string;
  /** Kurze Begründung, warum diese Seite trotz Ähnlichkeit einen eigenen Existenzgrund hat. */
  differentiation: string;
}

